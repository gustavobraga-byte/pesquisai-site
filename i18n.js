  var langWrap = document.getElementById('langWrap');
  var langBtn = document.getElementById('langBtn');
  var langMenu = document.getElementById('langMenu');

  function detectLang(){
    /* 1) escolha explícita do usuário (salva em localStorage) */
    var saved = null;
    try { saved = localStorage.getItem(STORAGE_KEY); } catch(e){}
    if (saved && I18N[saved]) return saved;
    /* 2) idioma(s) do navegador: navigator.languages (lista) + fallback language */
    var prefs = [];
    try {
      if (navigator.languages && navigator.languages.length) prefs = navigator.languages.slice();
      if (navigator.language) prefs.push(navigator.language);
      if (navigator.userLanguage) prefs.push(navigator.userLanguage);
    } catch(e){}
    for (var i = 0; i < prefs.length; i++) {
      var nav = (prefs[i] || '').toLowerCase();
      if (nav.indexOf('en') === 0) return 'en';
      if (nav.indexOf('fr') === 0) return 'fr';
      if (nav.indexOf('es') === 0) return 'es';
      if (nav.indexOf('zh') === 0) return 'zh';
      if (nav.indexOf('pt') === 0) return 'pt';
    }
    /* 3) padrão: português (idioma de origem do projeto) */
    return 'pt';
  }

  function t(key, lang){
    var dict = I18N[lang] || I18N.pt;
    return dict[key] !== undefined ? dict[key] : (I18N.pt[key] !== undefined ? I18N.pt[key] : key);
  }

  function apply(lang){
    if (!I18N[lang]) lang = 'pt';
    var dict = I18N[lang];

    document.documentElement.lang = lang === 'zh' ? 'zh-CN' : lang;
    document.title = t('title', lang);
    var meta = document.querySelector('meta[name="description"]');
    if (meta) meta.setAttribute('content', t('meta.desc', lang));

    /* texto simples */
    document.querySelectorAll('[data-i18n]').forEach(function(el){
      var k = el.getAttribute('data-i18n');
      if (dict[k] !== undefined) el.textContent = dict[k];
    });

    /* html (com marcação) */
    document.querySelectorAll('[data-i18n-html]').forEach(function(el){
      var k = el.getAttribute('data-i18n-html');
      if (dict[k] !== undefined) el.innerHTML = dict[k];
    });

    /* atributos */
    document.querySelectorAll('[data-i18n-attr]').forEach(function(el){
      var spec = el.getAttribute('data-i18n-attr');
      var parts = spec.split(';');
      var k = parts[0];
      var attrs = parts[1] ? parts[1].split(',') : ['aria-label'];
      if (dict[k] !== undefined) {
        attrs.forEach(function(a){
          el.setAttribute(a, dict[k]);
        });
      }
    });

    /* placeholders especiais {n} (ex.: "Etapa 01") */
    document.querySelectorAll('[data-i18n-n]').forEach(function(el){
      var k = el.getAttribute('data-i18n-n');
      var n = el.getAttribute('data-n') || '01';
      if (dict[k] !== undefined) el.textContent = dict[k].replace('{n}', n);
    });

    /* autores com {url} e {user} */
    document.querySelectorAll('[data-i18n-author]').forEach(function(el){
      var url = el.getAttribute('data-url');
      var user = el.getAttribute('data-user');
      if (dict['skill.author'] !== undefined) {
        el.innerHTML = dict['skill.author'].replace('{url}', url).replace('{user}', user);
      }
    });

    if (langMenu) {
      langMenu.querySelectorAll('.lang-option').forEach(function(opt){
        opt.classList.toggle('is-active', opt.getAttribute('data-lang') === lang);
      });
    }
  }

  function closeLangMenu(){
    if (langMenu) langMenu.classList.remove('open');
    if (langBtn) langBtn.setAttribute('aria-expanded', 'false');
  }

  function persist(lang){
    try { localStorage.setItem(STORAGE_KEY, lang); } catch(e){}
  }

  if (langBtn && langMenu) {
    langBtn.addEventListener('click', function(e){
      e.stopPropagation();
      var open = langMenu.classList.toggle('open');
      langBtn.setAttribute('aria-expanded', String(open));
    });
    langMenu.querySelectorAll('.lang-option').forEach(function(opt){
      opt.addEventListener('click', function(){
        var lang = opt.getAttribute('data-lang');
        persist(lang);
        apply(lang);
        closeLangMenu();
      });
    });
    document.addEventListener('click', function(e){
      if (langWrap && !langWrap.contains(e.target)) closeLangMenu();
    });
    document.addEventListener('keydown', function(e){
      if (e.key === 'Escape') closeLangMenu();
    });
  }

  /* expõe helper global para outros scripts (ex.: site.js) */
  window.PesquisAII18n = { t: t, apply: apply, getLang: detectLang };

  apply(detectLang());
